#!/usr/bin/env node
// The architecture diagram in DESIGN.md, from the graph.
//
//   node graph/diagram.mjs     (build.mjs runs it last)
//
// Groups every code node by its top-level area -- control_plane/<package>,
// ui/src/<area>, .omp/<part>, tests -- counts cross-area import/call edges,
// and writes a Mermaid `graph LR` of the areas with every edge of weight ≥ 3
// between the `<!-- arch:start -->` / `<!-- arch:end -->` markers. Importable:
// `diagram()` returns the Mermaid so generated.check.mjs can compare.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const DESIGN = join(here, '..', 'design', 'DESIGN.md')
const MIN = 3
const RELATIONS = new Set(['imports', 'imports_from', 'calls', 'references', 're_exports'])

export function areaOf(file) {
  if (!file) return null
  const p = file.split('/')
  if (p[0] === 'control_plane') return p.length > 2 ? `control_plane/${p[1]}` : 'control_plane'
  if (p[0] === 'ui' && p[1] === 'src') return p.length > 3 ? `ui/src/${p[2]}` : 'ui/src'
  if (p[0] === '.omp') return p[1] === 'design' ? '.omp/design' : `.omp/${p[1]}`
  if (p[0] === 'tests') return 'tests'
  if (p[0] === 'docker' || p[0] === 'docs' || p[0] === 'scripts') return p[0]
  return null
}

export function diagram(graphPath = join(here, 'graph.json')) {
  const g = JSON.parse(readFileSync(graphPath, 'utf8'))
  const area = new Map(g.nodes.map((n) => [n.id, areaOf(n.source_file)]))
  const weights = new Map()
  for (const e of g.links) {
    if (!RELATIONS.has(e.relation)) continue
    const a = area.get(e.source), b = area.get(e.target)
    if (!a || !b || a === b) continue
    const k = `${a}|${b}`
    weights.set(k, (weights.get(k) ?? 0) + 1)
  }
  const edges = [...weights].filter(([, w]) => w >= MIN).sort((x, y) => y[1] - x[1])
  const nodes = new Set(edges.flatMap(([k]) => k.split('|')))
  const id = (a) => a.replace(/[^A-Za-z0-9]/g, '_')
  const sub = (prefix, title) => {
    const members = [...nodes].filter((n) => n.startsWith(prefix)).sort()
    return members.length ? [`  subgraph sg_${id(prefix)}[${title}]`, ...members.map((m) => `    ${id(m)}["${m.slice(prefix.length) || m}"]`), '  end'] : []
  }
  const lines = ['graph LR', ...sub('control_plane/', 'control_plane'), ...sub('ui/src/', 'ui/src'), ...sub('.omp/', '.omp'), ...sub('tests', 'tests')]
  for (const n of nodes) if (!/^(control_plane\/|ui\/src\/|\.omp\/|tests)/.test(n)) lines.push(`  ${id(n)}["${n}"]`)
  for (const [k, w] of edges) { const [a, b] = k.split('|'); lines.push(`  ${id(a)} -->|${w}| ${id(b)}`) }
  return { mermaid: lines.join('\n'), edges: edges.length, areas: nodes.size }
}

export function render(graphPath) {
  const d = diagram(graphPath)
  return `<!-- arch:start -->\nGenerated by \`graph/diagram.mjs\` from \`.omp/graph/graph.json\`: ${d.areas} areas, ${d.edges} cross-area dependencies of weight ≥ ${MIN} (imports, calls, references). Rebuild: \`cd .omp && npm run graph:update\`.\n\n\`\`\`mermaid\n${d.mermaid}\n\`\`\`\n<!-- arch:end -->`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = readFileSync(DESIGN, 'utf8')
  const next = doc.replace(/<!-- arch:start -->[\s\S]*?<!-- arch:end -->/, render())
  if (next !== doc) writeFileSync(DESIGN, next)
  const d = diagram()
  console.log(`diagram: ${d.areas} areas, ${d.edges} edges -> DESIGN.md`)
}
