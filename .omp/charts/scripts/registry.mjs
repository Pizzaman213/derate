#!/usr/bin/env node
// registry.json: every chart -- id, name, category, intents, aliases, input schema ref,
// fields, samples, icon, README, status, and the last recorded test results (vitest
// JSON report + browser suites). Generated from the code and the result files, never
// edited by hand. `--check` fails when it is stale (ignoring timestamps and results).
//
//   node scripts/registry.mjs [--check]

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'registry.json')
const api = await import(pathToFileURL(join(root, 'dist', 'charts.esm.js')).href)
const icons = existsSync(join(root, 'icons', 'icons.json')) ? JSON.parse(readFileSync(join(root, 'icons', 'icons.json'), 'utf8')).icons : []
const vitest = existsSync(join(root, 'tests', '.results', 'vitest.json')) ? JSON.parse(readFileSync(join(root, 'tests', '.results', 'vitest.json'), 'utf8')) : null
const browser = existsSync(join(root, 'tests', '.results', 'browser.json')) ? JSON.parse(readFileSync(join(root, 'tests', '.results', 'browser.json'), 'utf8')) : null

function unitResults(id) {
  const file = vitest?.testResults?.find((t) => t.name.endsWith(`/types/${id}/${id}.test.ts`))
  if (!file) return null
  const passed = file.assertionResults.filter((a) => a.status === 'passed').length
  const failed = file.assertionResults.filter((a) => a.status === 'failed').length
  return { passed, failed }
}

export function buildRegistry() {
  const aliases = Object.entries(api.ALIASES)
  const charts = api.listCharts().map((c) => {
    const dir = join(root, 'types', c.id)
    const samples = existsSync(join(dir, 'samples')) ? readdirSync(join(dir, 'samples')).filter((f) => f.endsWith('.json')).sort().map((f) => `types/${c.id}/samples/${f}`) : []
    const icon = icons.find((i) => i.name === c.id)
    const unit = unitResults(c.id)
    const b = browser?.charts?.[c.id] ?? {}
    const suite = (k) => (b[k] ? { passed: b[k].passed, failed: b[k].failed } : null)
    const tests = { unit, visual: suite('visual'), layout: suite('layout'), a11y: suite('a11y'), perf: suite('perf') }
    const ran = Object.values(tests).filter(Boolean)
    const passing = ran.length > 0 && ran.every((t) => t.failed === 0)
    return {
      id: c.id,
      name: c.name,
      category: c.category,
      intents: c.intents,
      summary: c.summary,
      aliases: aliases.filter(([, v]) => v === c.id).map(([k]) => k),
      shape: c.shape,
      fields: c.fields,
      zoom: c.zoom,
      schema: `types/${c.id}/schema.ts`,
      entry: `types/${c.id}/index.ts`,
      readme: existsSync(join(dir, 'README.md')) ? `types/${c.id}/README.md` : null,
      test: existsSync(join(dir, `${c.id}.test.ts`)) ? `types/${c.id}/${c.id}.test.ts` : null,
      samples,
      icon: icon ? `icons/svg/${c.id}.svg` : null,
      status: passing && icon && samples.length >= 5 ? 'stable' : 'incomplete',
      tests: { ...tests, passing },
    }
  })
  return {
    $comment: 'GENERATED by scripts/registry.mjs (npm run charts:registry). Search this before building a chart (RULES.md #1).',
    version: 1,
    generated: new Date().toISOString(),
    count: charts.length,
    categories: Object.fromEntries([...new Set(charts.map((c) => c.category))].map((k) => [k, charts.filter((c) => c.category === k).map((c) => c.id)])),
    charts,
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const reg = buildRegistry()
  const strip = (r) => JSON.stringify({ ...r, generated: null, charts: r.charts.map((c) => ({ ...c, tests: null, status: null })) })
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null
    const stale = !cur || strip(cur) !== strip(reg)
    console.log(stale ? 'FAIL registry.json is stale — run: npm run charts:registry' : `registry: ${reg.count} charts, fresh`)
    process.exit(stale ? 1 : 0)
  }
  writeFileSync(OUT, JSON.stringify(reg, null, 2) + '\n')
  const inc = reg.charts.filter((c) => c.status !== 'stable')
  console.log(`registry: ${reg.count} charts -> ${relative(process.cwd(), OUT)}; ${reg.count - inc.length} stable${inc.length ? `, incomplete: ${inc.map((c) => c.id).join(', ')}` : ''}`)
}
