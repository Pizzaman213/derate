#!/usr/bin/env node
// charts:build -- generate types/all.ts (one import per chart folder), the data
// bundle source (samples + shared datasets), then bundle with esbuild:
//
//   dist/charts.esm.js    the API as an ES module (browser or node; no DOM touched at import)
//   dist/charts.iife.js   the same as a global, window.OmpCharts (gallery, tests, file://)
//   dist/charts-data.js   every sample and dataset, registering itself with OmpCharts
//
// `--check` only verifies that the generated sources are current.

import { build } from 'esbuild'
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')

export function chartIds() {
  return readdirSync(join(root, 'types'))
    .filter((d) => statSync(join(root, 'types', d)).isDirectory() && existsSync(join(root, 'types', d, 'index.ts')))
    .sort()
}

const camel = (id) => 'c_' + id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

export function allSource(ids = chartIds()) {
  return (
    '// GENERATED by scripts/build.mjs from the folders in types/ -- do not edit.\n' +
    ids.map((id) => `import ${camel(id)} from './${id}/index'`).join('\n') +
    `\n\nexport const ALL_CHARTS = [${ids.map(camel).join(', ')}]\n`
  )
}

export function dataSource(ids = chartIds()) {
  const samples = {}
  for (const id of ids) {
    const dir = join(root, 'types', id, 'samples')
    if (!existsSync(dir)) continue
    samples[id] = {}
    for (const f of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) samples[id][f.slice(0, -5)] = JSON.parse(readFileSync(join(dir, f), 'utf8'))
  }
  const datasets = {}
  const dsDir = join(root, 'datasets')
  if (existsSync(join(dsDir, 'datasets.json'))) {
    const reg = JSON.parse(readFileSync(join(dsDir, 'datasets.json'), 'utf8'))
    for (const d of reg.datasets ?? []) datasets[d.name] = JSON.parse(readFileSync(join(dsDir, d.file), 'utf8'))
  }
  return { samples, datasets }
}

const files = { all: join(root, 'types', 'all.ts') }

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const all = allSource()
  if (check) {
    const stale = !existsSync(files.all) || readFileSync(files.all, 'utf8') !== all
    console.log(stale ? 'FAIL types/all.ts is stale — run: npm run charts:build' : 'build: generated sources fresh')
    process.exit(stale ? 1 : 0)
  }
  writeFileSync(files.all, all)
  mkdirSync(join(root, 'dist'), { recursive: true })
  const common = { bundle: true, entryPoints: [join(root, 'index.ts')], platform: 'neutral', target: 'es2022', mainFields: ['module', 'main'], legalComments: 'none', logLevel: 'warning' }
  const t0 = Date.now()
  await build({ ...common, format: 'esm', outfile: join(root, 'dist', 'charts.esm.js') })
  await build({ ...common, format: 'iife', globalName: 'OmpCharts', outfile: join(root, 'dist', 'charts.iife.js'), minify: true })
  const data = dataSource()
  writeFileSync(join(root, 'dist', 'charts-data.js'), `/* GENERATED by scripts/build.mjs */\n(function(){var d=${JSON.stringify(data)};if(typeof OmpCharts!=='undefined'&&OmpCharts.registerData)OmpCharts.registerData(d);else (typeof globalThis!=='undefined'?globalThis:window).__ompChartsData=d;})();\n`)
  const sz = (f) => `${(statSync(join(root, 'dist', f)).size / 1024).toFixed(0)} KB`
  console.log(`build: ${chartIds().length} charts -> dist/charts.esm.js ${sz('charts.esm.js')}, charts.iife.js ${sz('charts.iife.js')}, charts-data.js ${sz('charts-data.js')} in ${Date.now() - t0} ms`)
}
