// The ownership map: which area of the repo owns what, how big it is, and who depends on it.
// `.omp/OWNERSHIP.md` is generated (`node scripts/ownership.mjs`); the gate only checks that
// it lists exactly the areas that exist and that each changed area says what it is for, so
// the map cannot go stale on size churn and an agent can trust its shape.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { changed, read } from './context.mjs'
import { budgetOf } from './budget.mjs'

const ROOTS = ['control_plane', 'ui/src', 'ui/src/tabs']
const SKIP_DIRS = new Set(['__pycache__', 'node_modules', 'dist', 'tabs', 'check'])
export const MAP = '.omp/OWNERSHIP.md'

const isDir = (p) => existsSync(p) && statSync(p).isDirectory()
const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n)
  return isDir(p) ? (SKIP_DIRS.has(n) ? [] : walk(p)) : /\.(py|tsx?|mjs|css)$/.test(n) ? [p] : []
})

/** First sentence of a README's first prose paragraph: the area's one-line job. */
export const responsibility = (dir) => {
  const f = join(dir, 'README.md')
  if (!existsSync(f)) return null
  const para = readFileSync(f, 'utf8').split('\n\n').map((s) => s.trim())
    .find((s) => s && !/^(#|\||```|<)/.test(s))
  return para ? para.replace(/\s+/g, ' ').split(/(?<=\.)\s/)[0].slice(0, 160) : null
}

export const areas = () => ROOTS.flatMap((r) => (isDir(r) ? readdirSync(r).map((n) => join(r, n)) : []))
  .filter((p) => isDir(p) && !SKIP_DIRS.has(p.split('/').pop()))
  .sort()

const importsOf = (dir) => {
  const found = new Set()
  for (const f of walk(dir).filter((p) => p.endsWith('.py'))) {
    for (const l of read(f)) {
      const m = l.match(/^\s*(?:from|import)\s+control_plane\.(\w+)/)
      if (m) found.add(`control_plane/${m[1]}`)
    }
  }
  found.delete(dir)
  return [...found].sort()
}

export const describe = (dir) => {
  const files = walk(dir)
  const sized = files.map((f) => [f, read(f).length])
  const [big, bigN] = sized.sort((a, b) => b[1] - a[1])[0] ?? ['-', 0]
  return { dir, job: responsibility(dir), files: files.length, lines: sized.reduce((s, [, n]) => s + n, 0),
    biggest: `${big.split('/').pop()} ${bigN}/${budgetOf(big)}`, imports: importsOf(dir) }
}

export const render = () => {
  const rows = areas().map(describe)
  const usedBy = (d) => rows.filter((r) => r.imports.includes(d)).map((r) => r.dir.replace('control_plane/', ''))
  return ['# Ownership map', '',
    'Generated by `node .omp/scripts/ownership.mjs`; do not edit. Read it before adding code: put new',
    'code in the area that already owns the concern, and check headroom with',
    '`node .omp/scripts/ownership.mjs --headroom <files>`. An area with no README line is a gap to fill.', '',
    '| area | responsibility | files | lines | biggest file (lines/budget) | imports | imported by |', '|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| \`${r.dir}\` | ${r.job ?? '**none: add a README line**'} | ${r.files} | ${r.lines} | ${r.biggest} | ${r.imports.map((i) => i.replace('control_plane/', '')).join(', ') || '-'} | ${usedBy(r.dir).join(', ') || '-'} |`),
    ''].join('\n')
}

const listed = () => (existsSync(MAP) ? [...readFileSync(MAP, 'utf8').matchAll(/^\| `([^`]+)` \|/gm)].map((m) => m[1]) : [])

export const steps = [
  { name: 'ownership map lists every area; changed areas say what they are for', run: () => {
    const have = areas(), mapped = listed(), out = []
    for (const a of have.filter((a) => !mapped.includes(a))) out.push(`${a} is not in ${MAP}: run node .omp/scripts/ownership.mjs`)
    for (const a of mapped.filter((a) => !have.includes(a))) out.push(`${a} is in ${MAP} but no longer exists: regenerate it`)
    for (const a of have.filter((a) => changed.some((c) => c.startsWith(a + '/')) && !responsibility(a))) out.push(`${a}/README.md has no one-line responsibility (first paragraph)`)
    return out
  } },
]
